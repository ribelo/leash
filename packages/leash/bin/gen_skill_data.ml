let read_file path = In_channel.with_open_bin path In_channel.input_all

let rec walk ~root path acc =
  if Sys.is_directory path then
    Sys.readdir path |> Array.to_list |> List.sort String.compare
    |> List.fold_left (fun acc name -> walk ~root (Filename.concat path name) acc) acc
  else
    let prefix = root ^ Filename.dir_sep in
    let relative =
      String.sub path (String.length prefix) (String.length path - String.length prefix)
    in
    (relative, read_file path) :: acc

let () =
  let root = Sys.argv.(1) in
  let files = walk ~root root [] |> List.rev in
  print_endline "(* Generated by gen_skill_data. Do not edit. *)";
  print_endline "let files : (string * string) list = [";
  List.iter
    (fun (relative, contents) -> Printf.printf "  (%S, %S);\n" relative contents)
    files;
  print_endline "]"
