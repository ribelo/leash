open Ox_caps

let read_file ~(caps : < Cap.fs_read ; .. >) path =
  Cap_stdlib.In_channel.with_open_bin ~caps path In_channel.input_all

let rec walk ~(caps : < Cap.fs_read ; .. >) ~root path acc =
  if Sys.is_directory path then
    Cap_sys.readdir ~caps path |> Array.to_list |> List.sort String.compare
    |> List.fold_left
         (fun acc name -> walk ~caps ~root (Filename.concat path name) acc)
         acc
  else
    let prefix = root ^ Filename.dir_sep in
    let relative =
      String.sub path (String.length prefix) (String.length path - String.length prefix)
    in
    (relative, read_file ~caps path) :: acc

let binding =
  match Sys.argv with
  | [| _; _ |] -> "files"
  | [| _; _; name |]
    when name <> ""
         && String.for_all
              (function 'a' .. 'z' | 'A' .. 'Z' | '0' .. '9' | '_' -> true | _ -> false)
              name ->
      name
  | _ -> invalid_arg "gen_skill_data ROOT [BINDING]"

let run ~(caps : < Cap.fs_read ; Cap.stdout ; .. >) () =
  let root = Sys.argv.(1) in
  let files = walk ~caps ~root root [] |> List.rev in
  Cap_stdlib.print_endline ~caps "(* Generated by gen_skill_data. Do not edit. *)";
  Cap_stdlib.printf ~caps "let %s : (string * string) list = [\n" binding;
  List.iter
    (fun (relative, contents) ->
      Cap_stdlib.printf ~caps "  (%S, %S);\n" relative contents)
    files;
  Cap_stdlib.print_endline ~caps "]"

let () =
  let caps = (Ox_caps_door.powerbox () :> < Cap.fs_read ; Cap.stdout >) in
  run ~caps ()
